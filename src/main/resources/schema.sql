DROP TABLE IF EXISTS appointments;
DROP TABLE IF EXISTS availability_slots;
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS providers;
DROP TABLE IF EXISTS users;

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'PROVIDER'))
);

CREATE TABLE providers (
    provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    bio VARCHAR(1000),
    CONSTRAINT fk_providers_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT uq_providers_user UNIQUE (user_id)
);

CREATE TABLE services (
    service_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    duration_minutes INT NOT NULL,
    CONSTRAINT fk_services_provider FOREIGN KEY (provider_id) REFERENCES providers (provider_id),
    CONSTRAINT ck_services_duration CHECK (duration_minutes > 0)
);

CREATE TABLE availability_slots (
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    CONSTRAINT fk_slots_service FOREIGN KEY (service_id) REFERENCES services (service_id),
    CONSTRAINT ck_slots_time CHECK (end_time > start_time),
    CONSTRAINT uq_slots_service_window UNIQUE (service_id, start_time, end_time)
);

CREATE TABLE appointments (
    appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_appointments_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_appointments_slot FOREIGN KEY (slot_id) REFERENCES availability_slots (slot_id),
    CONSTRAINT uq_appointment_slot UNIQUE (slot_id)
);
