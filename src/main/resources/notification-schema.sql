CREATE TABLE IF NOT EXISTS notification_outbox (
 event_id VARCHAR(120) PRIMARY KEY, recipient VARCHAR(255) NOT NULL,
 type VARCHAR(40) NOT NULL, message VARCHAR(1000) NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'PENDING', attempts INT NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, last_error VARCHAR(100),
 CONSTRAINT ck_outbox_state CHECK (state IN ('PENDING','SENT','FAILED'))
);
CREATE TABLE IF NOT EXISTS notification_receipts (
 event_id VARCHAR(120) PRIMARY KEY, payload_hash VARCHAR(64) NOT NULL,
 recipient VARCHAR(255) NOT NULL, type VARCHAR(40) NOT NULL, message VARCHAR(1000) NOT NULL,
 received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
